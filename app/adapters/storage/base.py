"""Repository protocols. Implementations: in-memory (tests/CLI) and Firestore (production)."""

from __future__ import annotations

from datetime import datetime
from typing import Protocol

from app.domain.models import (
    Appointment,
    AppointmentStatus,
    ApprovalRequest,
    AuditEntry,
    Conversation,
    Patient,
    WaitlistEntry,
)


class StorageError(Exception):
    pass


class PatientRepo(Protocol):
    async def get(self, phone: str) -> Patient | None: ...
    async def save(self, patient: Patient) -> None: ...
    async def list_all(self) -> list[Patient]: ...


class AppointmentRepo(Protocol):
    async def get(self, appointment_id: str) -> Appointment | None: ...
    async def save(self, appointment: Appointment) -> None: ...
    async def list_by_patient(self, phone: str) -> list[Appointment]: ...
    async def list_between(
        self, start: datetime, end: datetime, *, status: AppointmentStatus | None = None
    ) -> list[Appointment]:
        """Appointments whose start is in [start, end), sorted by start."""
        ...


class ConversationRepo(Protocol):
    async def get(self, phone: str) -> Conversation | None: ...
    async def save(self, conversation: Conversation) -> None: ...
    async def delete(self, phone: str) -> None: ...
    async def list_updated_before(self, when: datetime) -> list[Conversation]: ...


class ProcessedMessageRepo(Protocol):
    async def claim(self, message_id: str, at: datetime) -> bool:
        """Atomically mark a message as processed. Returns False if it was already claimed (duplicate)."""
        ...

    async def purge_before(self, when: datetime) -> int: ...


class ApprovalRepo(Protocol):
    async def next_code(self) -> int: ...
    async def save(self, approval: ApprovalRequest) -> None: ...
    async def get_by_code(self, code: int) -> ApprovalRequest | None: ...
    async def list_pending(self) -> list[ApprovalRequest]: ...


class WaitlistRepo(Protocol):
    async def save(self, entry: WaitlistEntry) -> None: ...
    async def list_active(self, procedure_id: str | None = None) -> list[WaitlistEntry]:
        """Active entries, oldest first."""
        ...


class AuditRepo(Protocol):
    async def append(self, entry: AuditEntry) -> None: ...


class Storage(Protocol):
    @property
    def patients(self) -> PatientRepo: ...
    @property
    def appointments(self) -> AppointmentRepo: ...
    @property
    def conversations(self) -> ConversationRepo: ...
    @property
    def processed(self) -> ProcessedMessageRepo: ...
    @property
    def approvals(self) -> ApprovalRepo: ...
    @property
    def waitlist(self) -> WaitlistRepo: ...
    @property
    def audit(self) -> AuditRepo: ...
